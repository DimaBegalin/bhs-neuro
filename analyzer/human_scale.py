def to_scale(value: float, rest: float, spread: float = 2.0) -> int:
    """Показатель в шкале 0-100, где 50 это покой самого ребёнка.

    Разброс подобран так, чтобы двукратное отклонение от покоя давало
    примерно 75 или 25 баллов: шкала должна двигаться заметно, но не улетать
    в край от любого шороха.
    """
    if rest <= 0:
        return 50
    ratio = value / rest
    if ratio <= 0:
        return 0
    import math
    score = 50 * (1 + math.tanh(math.log(ratio) / spread))
    return int(round(max(0, min(100, score))))


def verdict(score: int, metric: str) -> str:
    """Короткая словесная оценка вместо числа."""
    meta = METRICS[metric]
    if score >= 65:
        return meta["high"]
    if score <= 35:
        return meta["low"]
    return "как обычно"


def tempo_words(iaf: float | None) -> tuple[str, str]:
    """Частота альфа-пика человеческим языком.

    Родителю слово «герц» не говорит ничего, а вот «темп мозга» и понятная
    норма говорят. Диапазон 8-12 это общепринятая норма для подростка.
    """
    if iaf is None:
        return ("не определён", "сигнал был неустойчивым, замер стоит повторить")
    if iaf < 8.5:
        return ("спокойный", "мозг работает размеренно, ему комфортнее без спешки")
    if iaf > 11.0:
        return ("быстрый", "мозг обрабатывает информацию быстро, любит темп")
    return ("средний", "обычный темп обработки информации для подростка")
