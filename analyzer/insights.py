# -*- coding: utf-8 -*-
"""Нейроинсайты: короткие слова для родителя, собранные из измеренного.

Каждый инсайт держится на конкретном числе замера. Слова тёплые, но ни одно
не выдумано: правило генерации видно прямо в коде.
"""

THINKING = {
    "spatial": ("Строитель", "пространственное мышление",
                "видит форму, объём и то, как детали складываются в целое"),
    "numeric": ("Алгоритмист", "логико-числовое мышление",
                "раскладывает задачу на шаги и держит логику до конца"),
    "verbal": ("Коммуникатор", "словесно-смысловое мышление",
               "чувствует значения слов и связи между смыслами"),
    "working_memory": ("Диспетчер", "оперативная память",
                       "удерживает несколько задач в голове одновременно"),
}

TRAJECTORY = {
    "spatial": [
        ("Сейчас, 7-9 класс", "робототехника, 3D-моделирование, шахматы, черчение"),
        ("Профиль, 10-11 класс", "физико-математическое или архитектурное направление, олимпиады по геометрии и физике"),
        ("Дальше", "архитектура, инженерия, хирургия и стоматология, промышленный дизайн"),
    ],
    "numeric": [
        ("Сейчас, 7-9 класс", "олимпиадная математика, программирование, логические клубы"),
        ("Профиль, 10-11 класс", "физмат или IT-профиль, олимпиады по математике и информатике"),
        ("Дальше", "программирование, аналитика данных, финансы, экономика"),
    ],
    "verbal": [
        ("Сейчас, 7-9 класс", "дебаты, школьные медиа, иностранные языки"),
        ("Профиль, 10-11 класс", "гуманитарный или языковой профиль, олимпиады по языкам"),
        ("Дальше", "право, международные отношения, маркетинг, журналистика"),
    ],
    "working_memory": [
        ("Сейчас, 7-9 класс", "шахматы, программирование, музыкальный инструмент"),
        ("Профиль, 10-11 класс", "IT или проектный профиль, командные конкурсы"),
        ("Дальше", "управление проектами, IT-архитектура, исследовательская работа"),
    ],
}


def build_insights(cards, scores, timeline, iaf, pulse, human_names) -> dict:
    best = cards[0]
    top = best["domain"]
    badge, mind_name, mind_line = THINKING[top]

    insights = [{
        "word": badge,
        "title": mind_name.capitalize(),
        "fact": "точность %d%% при затратах ниже остальных доменов"
                % round(best["accuracy"] * 100),
        "study": mind_line.capitalize() + ": это ведущий канал, его нагружаем смело.",
        "color": "#F16B14",
    }]

    warmup = timeline.get("warmup")
    if warmup:
        if warmup["mean_s"] <= 6:
            insights.append({"word": "Быстрый старт", "title": "включение в задачу",
                             "fact": "выходит на рабочую включённость за %.0f секунд"
                                     % warmup["mean_s"],
                             "study": "Можно начинать занятие сразу с главного.",
                             "color": "#22B57C"})
        else:
            insights.append({"word": "Дизель", "title": "включение с разбегом",
                             "fact": "на разгон уходит около %.0f секунд"
                                     % warmup["mean_s"],
                             "study": "Первые минуты отдавать простым заданиям, "
                                      "по первым ответам не судить.",
                             "color": "#5B8DEF"})

    reaction = timeline.get("error_reaction")
    if reaction:
        if reaction["delta"] <= 2:
            insights.append({"word": "Несгибаемый", "title": "отношение к ошибке",
                             "fact": "напряжение после ошибки не растёт: %d против %d"
                                     % (reaction["after_error"], reaction["after_ok"]),
                             "study": "Неудача не выбивает: можно давать задачи "
                                      "на вырост.",
                             "color": "#22B57C"})
        elif reaction["delta"] >= 8:
            insights.append({"word": "Перфекционист", "title": "отношение к ошибке",
                             "fact": "после ошибки напряжение подскакивает на %d пунктов"
                                     % round(reaction["delta"]),
                             "study": "Хвалить за ход решения, учить проходить "
                                      "ошибку без остановки.",
                             "color": "#F0666B"})

    fatigue = timeline.get("fatigue")
    if fatigue:
        if fatigue["delta_pct"] < 15:
            insights.append({"word": "Марафонец", "title": "выносливость",
                             "fact": "усилие к концу теста выросло всего на %d%%"
                                     % max(fatigue["delta_pct"], 0),
                             "study": "Выдерживает полное занятие, объём можно "
                                      "наращивать.",
                             "color": "#F4C15A"})
        else:
            insights.append({"word": "Спринтер", "title": "выносливость",
                             "fact": "к концу теста усилие выросло на %d%%"
                                     % fatigue["delta_pct"],
                             "study": "Сильные короткие подходы: дробить работу "
                                      "на отрезки по 15-20 минут.",
                             "color": "#F4C15A"})

    if timeline.get("flow_pct", 0) >= 25:
        insights.append({"word": "В потоке", "title": "рабочее состояние",
                         "fact": "%d%% времени работал включённо и без перегрузки"
                                 % timeline["flow_pct"],
                         "study": "Умеет входить в поток: беречь от отвлечений, "
                                  "поток дорого стоит.",
                         "color": "#C77DF0"})

    if iaf:
        word = "Размеренный процессор" if iaf < 9.5 else "Быстрый процессор"
        line = ("думает основательно, не любит гонку"
                if iaf < 9.5 else "обрабатывает информацию быстро, любит темп")
        insights.append({"word": word, "title": "темп мозга %.1f Гц" % iaf,
                         "fact": "личная частота спокойного ритма",
                         "study": line.capitalize() + ".", "color": "#5B8DEF"})

    if pulse and pulse.get("ok"):
        spread = pulse["bpm_max"] - pulse["bpm_min"]
        if spread <= 30:
            insights.append({"word": "Ровное сердце", "title": "пульс %d уд/мин"
                             % pulse["bpm_median"],
                             "fact": "разброс за тест всего %d ударов" % spread,
                             "study": "Тело держит нагрузку спокойно, стресс не "
                                      "уходит в физиологию.",
                             "color": "#FF7AA2"})
        else:
            insights.append({"word": "Живое сердце", "title": "пульс %d уд/мин"
                             % pulse["bpm_median"],
                             "fact": "разброс за тест %d ударов" % spread,
                             "study": "Сердце откликается на нагрузку: дыхание и "
                                      "паузы помогут держать ровнее.",
                             "color": "#FF7AA2"})

    worst = cards[-1]
    specialist = (
        "Ведущий канал по замеру: %s (%s). Точность %d%% при энергозатратах ниже "
        "остальных доменов: результат достаётся дёшево, это ресурс для профиля и "
        "олимпиад. Дороже всего обходится «%s»: %d%% точности при напряжении %d "
        "из 100, что говорит о цене, но ничего о потолке. %s %s Черновик собран "
        "алгоритмом по данным замера, финальную трактовку даёт специалист на "
        "разборе."
        % (human_names[top][0].lower(), mind_name,
           round(best["accuracy"] * 100),
           human_names[worst["domain"]][0],
           round(worst["accuracy"] * 100), scores[worst["domain"]]["stress"],
           ("Включается быстро." if warmup and warmup["mean_s"] <= 6
            else "Нужен короткий разбег в начале работы." if warmup else ""),
           ("Ошибку проходит спокойно." if reaction and reaction["delta"] <= 2
            else "Ошибка заметно поднимает напряжение, с этим стоит работать."
            if reaction and reaction["delta"] >= 8 else ""))
    )

    return {"insights": insights, "specialist": specialist,
            "trajectory": TRAJECTORY[top],
            "trajectory_title": human_names[top][0]}
