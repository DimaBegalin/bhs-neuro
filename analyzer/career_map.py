"""Профориентационная карта: от измеренного профиля к направлениям.

Логика честная и объяснимая: мы не читаем профессию из мозга. Мы смотрим,
на каком типе задач ребёнок даёт результат в ресурсном состоянии, и называем
направления, где это мышление составляет ядро ежедневной работы. Каждая
рекомендация опирается на конкретные измеренные числа.
"""

CLUSTERS = {
    "spatial": {
        "cluster": "Пространство и образы",
        "core": "образное и пространственное мышление",
        "profs": ["Архитектура и урбанистика", "Медицина: хирургия, стоматология",
                  "Инженерия и робототехника", "Промышленный дизайн и геймдев",
                  "Авиация и навигация"],
    },
    "numeric": {
        "cluster": "Логика и расчёт",
        "core": "работа с числами и закономерностями",
        "profs": ["Финансы и аналитика данных", "Программирование",
                  "Экономика", "Физика и инженерные расчёты",
                  "Актуарные и страховые расчёты"],
    },
    "verbal": {
        "cluster": "Слово и коммуникация",
        "core": "работа со смыслами и формулировками",
        "profs": ["Право", "Международные отношения",
                  "Маркетинг и коммуникации", "Журналистика и медиа",
                  "Преподавание"],
    },
    "working_memory": {
        "cluster": "Управление и удержание",
        "core": "удержание многих задач в голове одновременно",
        "profs": ["Управление проектами", "Исследовательская работа",
                  "IT-архитектура", "Диагностическая медицина",
                  "Операционный менеджмент"],
    },
}

ARCHETYPES = {
    frozenset(("spatial", "numeric")): (
        "Конструктор", "видит систему в объёме и умеет её просчитать"),
    frozenset(("spatial", "working_memory")): (
        "Визуальный стратег", "держит картину целиком и планирует наперёд"),
    frozenset(("spatial", "verbal")): (
        "Автор пространств", "переводит образы в решения, понятные людям"),
    frozenset(("numeric", "working_memory")): (
        "Аналитик", "раскладывает сложное на шаги и не теряет нить"),
    frozenset(("numeric", "verbal")): (
        "Системный переговорщик", "соединяет логику и слово"),
    frozenset(("verbal", "working_memory")): (
        "Координатор", "удерживает людей и задачи в одном поле"),
}


def build_career(cards: list, scores: dict, human_names: dict) -> dict:
    """cards это домены профиля, scores это шкалы 0-100 по каждому домену."""
    fits = []
    for card in cards:
        d = card["domain"]
        s = scores[d]
        fit = round(0.45 * card["accuracy"] * 100
                    + 0.30 * (100 - s["stress"])
                    + 0.25 * s["focus"])
        meta = CLUSTERS[d]
        why = ("Точность %d%% при напряжении %d из 100 и концентрации %d из 100. "
               "Ядро этих профессий держится на том же типе мышления: %s."
               % (round(card["accuracy"] * 100), s["stress"], s["focus"],
                  meta["core"]))
        fits.append({"domain": d, "fit": fit, "why": why,
                     "cluster": meta["cluster"], "profs": meta["profs"]})
    fits.sort(key=lambda f: -f["fit"])

    top_pair = frozenset((fits[0]["domain"], fits[1]["domain"]))
    name, tagline = ARCHETYPES.get(
        top_pair, ("Универсал", "работает ровно в разных типах задач"))

    worst = fits[-1]
    worst_name = human_names[worst["domain"]][0]
    caution = ("Дороже всего дались задачи направления «%s»: напряжение %d из 100. "
               "Дорога туда открыта, вопрос в цене: профессии с ежедневной "
               "многочасовой нагрузкой этого типа будут стоить ребёнку больше "
               "сил, чем остальным. Если выбор упадёт туда, нагрузку надо "
               "дозировать короткими отрезками."
               % (worst_name, scores[worst["domain"]]["stress"]))

    return {"archetype": {"name": name, "tagline": tagline,
                          "from": [fits[0]["domain"], fits[1]["domain"]]},
            "fits": fits, "caution": caution}
